     *
     * @param \DateTime|null $dispute_date When the dispute was raised. Chargeback-only, optional.
     *
     * @return self
     */
    public function setDisputeDate($dispute_date)
    {
        if (is_null($dispute_date)) {
            array_push($this->openAPINullablesSetToNull, 'dispute_date');
        } else {
            $nullablesSetToNull = $this->getOpenAPINullablesSetToNull();
            $index = array_search('dispute_date', $nullablesSetToNull);
            if ($index !== FALSE) {
                unset($nullablesSetToNull[$index]);
                $this->setOpenAPINullablesSetToNull($nullablesSetToNull);
            }
        }
        $this->container['dispute_date'] = $dispute_date;

        return $this;
    }
